class SpendMeter:
    """Provider-reported OpenRouter spend (GET /api/v1/key data.usage delta) with a
    ClassifyResult.usage fallback; DeepSeek-direct calls always at the peak price.

    total = measured OpenRouter delta at the last good checkpoint
          + OpenRouter estimates since that checkpoint
          + DeepSeek estimates (never measured).
    The /key usage is per key, so concurrent spend on the same key (e.g. the live cron)
    is counted too — conservative."""

    def __init__(
        self,
        cap: float,
        ledger_path: pathlib.Path | None,
        *,
        api_key: str | None = None,
        http_get: Callable | None = None,
        checkpoint_every: int = CHECKPOINT_EVERY,
        or_prices: tuple[float, float] = (OPENROUTER_MAX_IN, OPENROUTER_MAX_OUT),
        ds_prices: tuple[float, float] = (DEEPSEEK_PEAK_IN, DEEPSEEK_PEAK_OUT),
        next_call_ceiling: float | None = None,
    ):
        self.cap = float(cap)
        self.ledger_path = ledger_path
        self.api_key = api_key
        self._http_get = http_get
        self.checkpoint_every = checkpoint_every
        self.or_prices = or_prices
        self.ds_prices = ds_prices
        if next_call_ceiling is None:
            # One classify() may, on a breaker trip, re-dispatch a 5-item streak to
            # the backup (6 calls), and an empty answer is re-called once (x2).
            per_call = (5000 * max(or_prices[0], ds_prices[0])
                        + 512 * max(or_prices[1], ds_prices[1])) / 1e6
            next_call_ceiling = 6 * 2 * per_call
        self.next_call_ceiling = next_call_ceiling
        self.start_usage: float | None = None
        self.last_usage: float | None = None
        self.or_measured = 0.0
        self.or_estimate_since_checkpoint = 0.0
        self.ds_estimate = 0.0
        self.calls = 0
        self.checkpoints = 0
        self.measured_checkpoints = 0

    # -- provider-reported usage ------------------------------------------------
    def _fetch_usage(self) -> float | None:
        if not self.api_key:
            return None
        try:
            import requests

            get = self._http_get or requests.get
            resp = get(
                OPENROUTER_KEY_URL,
                headers={"Authorization": f"Bearer {self.api_key}"},
                timeout=15,
            )
            if getattr(resp, "status_code", None) != 200:
                return None
            usage = (resp.json().get("data") or {}).get("usage")
            if isinstance(usage, bool) or not isinstance(usage, (int, float)):
                return None
            return float(usage)
        except Exception as exc:  # noqa: BLE001 — fall back to estimates
            logger.warning("spend meter: /key usage unavailable (%s)", type(exc).__name__)
            return None

    def start(self) -> None:
        self.start_usage = self._fetch_usage()
        self.last_usage = self.start_usage
        self.persist()

    def checkpoint(self) -> None:
        self.checkpoints += 1
        if self.start_usage is None:
            return
        usage = self._fetch_usage()
        if usage is None:
            return
        self.last_usage = usage
        self.or_measured = max(0.0, usage - self.start_usage)
        self.or_estimate_since_checkpoint = 0.0
        self.measured_checkpoints += 1

    # -- estimates ----------------------------------------------------------------
    def estimate(self, res) -> float:
        usage = getattr(res, "usage", None) or {}
        pt = usage.get("prompt_tokens") or 0
        ct = usage.get("completion_tokens") or 0
        mult = 2 if getattr(res, "error", None) == "empty_content" else 1
        if getattr(res, "provider", None) == "deepseek":
            return mult * (pt * self.ds_prices[0] + ct * self.ds_prices[1]) / 1e6
        cost = usage.get("cost")
        if isinstance(cost, (int, float)) and not isinstance(cost, bool):
            return mult * float(cost)
        return mult * (pt * self.or_prices[0] + ct * self.or_prices[1]) / 1e6

    def charge(self, res) -> None:
        cost = self.estimate(res)
        if getattr(res, "provider", None) == "deepseek":
            self.ds_estimate += cost
        else:
            self.or_estimate_since_checkpoint += cost
        self.calls += 1
        if self.checkpoint_every and self.calls % self.checkpoint_every == 0:
            self.checkpoint()
        self.persist()

    @property
    def total(self) -> float:
        return self.or_measured + self.or_estimate_since_checkpoint + self.ds_estimate

    def would_exceed(self) -> bool:
        return self.total + self.next_call_ceiling > self.cap

    def persist(self) -> None:
        if self.ledger_path is None:
            return
        ledger = {
            "cap_usd": self.cap,
            "total_usd": round(self.total, 6),
            "openrouter_measured_usd": round(self.or_measured, 6),
            "openrouter_estimate_since_checkpoint_usd": round(self.or_estimate_since_checkpoint, 6),
            "deepseek_estimate_usd": round(self.ds_estimate, 6),
            "calls": self.calls,
            "checkpoints": self.checkpoints,
            "measured_checkpoints": self.measured_checkpoints,
            "method": "measured+estimate" if self.start_usage is not None else "estimate_only",
            "next_call_ceiling_usd": round(self.next_call_ceiling, 6),
            "updated": _iso_z(dt.datetime.now(dt.timezone.utc)),
        }
        self.ledger_path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.ledger_path.with_suffix(self.ledger_path.suffix + ".tmp")
        tmp.write_bytes(json.dumps(ledger, indent=2).encode("utf-8"))
        os.replace(tmp, self.ledger_path)


