def load_cache(path: pathlib.Path) -> dict[str, dict]:
    """Last line per id wins. Missing file → {}. A torn last line is ignored."""
    cache: dict[str, dict] = {}
    if not path.exists():
        return cache
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                logger.warning("cache: skipping a malformed line")
                continue
            if isinstance(rec, dict) and rec.get("id"):
                cache[rec["id"]] = rec
    return cache


def _is_final(rec: dict | None) -> bool:
    return bool(rec) and rec.get("outcome") in FINAL_OUTCOMES


def _cache_line(key: str, res, now: dt.datetime) -> dict:
    output = res.output.model_dump() if res.output is not None else None
    return {
        "id": key,
        "outcome": getattr(res.outcome, "value", res.outcome),
        "status_code": res.status_code,
        "error": res.error,
        "output": output,
        "provider": res.provider,
        "model": res.model,
        "served_by": getattr(res, "served_by", None),
        "usage": getattr(res, "usage", None),
        "ts": _iso_z(now),
    }


