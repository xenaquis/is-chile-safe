def _ok_items(rows: list[dict], cache: dict[str, dict]) -> list[tuple[dict, dict]]:
    return [(r, cache[r["id"]]) for r in rows
            if cache.get(r["id"], {}).get("outcome") == "ok" and cache[r["id"]].get("output")]


def _published_headlines(row: dict, output: dict) -> dict:
    """What run_apply would publish (premortem R-16): the outlet's verbatim headline
    (title_src) and the guarded title_en — never the classifier's title_es."""
    from pipeline.news.feeds import source_headline
    from pipeline.news.fidelity import guard_title_en

    outlet = row.get("outlet") or ""
    title_src = source_headline(row.get("title") or "", outlet)
    title_en, fell_back = guard_title_en(title_src, output.get("title_en"), outlet)
    return {"title_src": title_src, "title_en": title_en, "title_en_fallback": fell_back}


def run_review(rows: list[dict], cache: dict[str, dict], out=None) -> int:
    out = out or sys.stdout
    hits = 0
    for row, rec in _ok_items(rows, cache):
        output = rec["output"]
        shown = _published_headlines(row, output)
        text = " ".join([row.get("title") or "", row.get("description") or "",
                         shown["title_src"]])
        if REVIEW_RE.search(text):
            hits += 1
            print(json.dumps({
                "id": row["id"], "date": row.get("date"), "family": output.get("family"),
                **shown, "source_title": row.get("title"),
            }, ensure_ascii=False), file=out)
    print(f"review_hits={hits}", file=out)
    return EXIT_OK


def stratum_of(row: dict) -> str:
    host = (urlparse(row.get("url") or "").hostname or "").lower()
    if host == "news.google.com":
        return STRATUM_GNEWS
    if NON_CHILE_RE.search(row.get("title") or "") or NON_CHILE_RE.search(row.get("description") or ""):
        return STRATUM_NON_CHILE
    return STRATUM_RANDOM


def run_audit_sample(
    rows: list[dict],
    cache: dict[str, dict],
    n: int,
    seed: int,
    out_path: pathlib.Path,
    *,
    exclude_ids: set[str] = frozenset(),
    withhold_ids: set[str] = frozenset(),
    out=None,
) -> int:
    from pipeline.news import resolver

    out = out or sys.stdout

    ok = [(r, c) for r, c in _ok_items(rows, cache) if r["id"] not in exclude_ids]
    by_stratum: dict[str, list[tuple[dict, dict]]] = {s: [] for s in STRATA}
    for r, c in ok:
        by_stratum[stratum_of(r)].append((r, c))

    # BF-03: a DEFINED stratum with 0 candidates (before withholding) → exit 5.
    empty = [s for s in STRATA if not by_stratum[s]]
    for s in STRATA:
        print(f"stratum {s}: cached_ok={len(by_stratum[s])}", file=out)
    if empty:
        print(f"stratum definition broken: 0 candidates in {', '.join(empty)} — exit 5", file=out)
        return EXIT_STRATUM

    pools = {s: sorted((p for p in by_stratum[s] if p[0]["id"] not in withhold_ids),
                       key=lambda p: p[0]["id"]) for s in STRATA}
    quotas = {STRATUM_GNEWS: math.ceil(0.4 * n), STRATUM_NON_CHILE: math.ceil(0.2 * n)}
    quotas[STRATUM_RANDOM] = max(0, n - quotas[STRATUM_GNEWS] - quotas[STRATUM_NON_CHILE])

    rng = random.Random(seed)
    sample: list[tuple[str, dict, dict]] = []
    shortfall = 0
    for s in (STRATUM_GNEWS, STRATUM_NON_CHILE):
        pool = pools[s]
        take = min(quotas[s], len(pool))
        if take < quotas[s]:
            shortfall += quotas[s] - take
            print(f"shortfall {s}: quota={quotas[s]} available={len(pool)} "
                  f"(filled from {STRATUM_RANDOM})", file=out)
        picked = rng.sample(pool, take)
        sample += [(s, r, c) for r, c in picked]
    rand_pool = pools[STRATUM_RANDOM]
    want = quotas[STRATUM_RANDOM] + shortfall
    take = min(want, len(rand_pool))
    if take < want:
        print(f"shortfall {STRATUM_RANDOM}: wanted={want} available={len(rand_pool)} "
              f"(sample has {len(sample) + take} of {n})", file=out)
    sample += [(STRATUM_RANDOM, r, c) for r, c in rng.sample(rand_pool, take)]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for s, r, c in sample:
        o = c["output"]
        resolved = resolver.resolve_cut(o.get("commune_name"), o.get("region_hint")) \
            if o.get("commune_name") else None
        lines.append(json.dumps({
            "id": r["id"], "stratum": s,
            "title": r.get("title"), "description": r.get("description"),
            "url": r.get("url"), "outlet": r.get("outlet"), "date": r.get("date"),
            "output": {
                "commune_name": o.get("commune_name"), "region_hint": o.get("region_hint"),
                "cut": resolved[0] if resolved else None,
                "slug": resolved[1] if resolved else None,
                "family": o.get("family"), **_published_headlines(r, o),
                "confidence": o.get("confidence"),
            },
            "model": f"{c.get('provider')}:{c.get('model')}",
        }, ensure_ascii=False))
    out_path.write_bytes(("\n".join(lines) + ("\n" if lines else "")).encode("utf-8"))
    counts = Counter(s for s, _, _ in sample)
    for s in STRATA:
        print(f"sampled {s}={counts.get(s, 0)}", file=out)
    print(f"sampled_total={len(sample)} seed={seed} out={out_path}", file=out)
    return EXIT_OK


