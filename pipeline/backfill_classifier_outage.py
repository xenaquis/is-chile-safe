def _month_files(data_dir: pathlib.Path, since: dt.datetime) -> list[pathlib.Path]:
    rejected_dir = data_dir / "rejected"
    if not rejected_dir.is_dir():
        return []
    since_month = since.strftime("%Y-%m")
    return [
        p for p in sorted(rejected_dir.glob("[0-9][0-9][0-9][0-9]-[0-9][0-9].json"))
        if p.stem >= since_month
    ]


def _load_envelope(path: pathlib.Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not isinstance(data.get("items"), list):
        raise ValueError(f"{path}: not a rejected envelope")
    return data


def _is_selected(row: dict, since: dt.datetime) -> bool:
    if row.get("rejection_stage") != STAGE_SELECTED:
        return False
    first_seen = parse_dt(row.get("first_seen"))
    return first_seen is not None and first_seen >= since


def _scan(data_dir: pathlib.Path, since: dt.datetime) -> list[tuple[str, dict]]:
    """(file name, row) of every selected row, deduped by id (first occurrence wins)."""
    out: list[tuple[str, dict]] = []
    seen_ids: set[str] = set()
    for path in _month_files(data_dir, since):
        for row in _load_envelope(path)["items"]:
            if not isinstance(row, dict) or not _is_selected(row, since):
                continue
            rid = row.get("id")
            if not rid or rid in seen_ids:
                continue
            seen_ids.add(rid)
            out.append((path.name, row))
    return out


def _order_key(row: dict):
    d = _parse_date(row.get("date")) or dt.date.min
    tie = (row.get("first_seen") or "", row.get("id") or "")
    if PRIORITY_START <= d <= PRIORITY_END:
        return (0, d.toordinal(), *tie)
    return (1, -d.toordinal(), *tie)


def select_outage_rows(data_dir: pathlib.Path, since: dt.datetime | str = DEFAULT_SINCE) -> list[dict]:
    """Outage rows, datetime-parsed, deduped by id, month files >= the since month.

    ORDERED (G-11/R-07): dates 2026-09-05..2026-09-22 ascending first, then the rest
    by date descending."""
    since_dt = parse_dt(since) if isinstance(since, str) else since
    if since_dt is None:
        raise ValueError(f"invalid since: {since!r}")
    rows = [row for _, row in _scan(pathlib.Path(data_dir), since_dt)]
    return sorted(rows, key=_order_key)


def _frozen(row: dict) -> bool:
    fs = parse_dt(row.get("first_seen"))
    return fs is not None and fs <= parse_dt(FROZEN_MAX_FIRST_SEEN)


