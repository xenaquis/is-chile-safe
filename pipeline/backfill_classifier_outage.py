def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="NREC-09 backfill of the Sept-2026 classifier outage")
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--dry-run", action="store_true", help="counts only, zero writes")
    mode.add_argument("--classify", action="store_true", help="classify into --cache (no data/ writes)")
    mode.add_argument("--apply", action="store_true", help="apply --cache to data/incidents")
    mode.add_argument("--review", action="store_true", help="print R-06 regex hits among cached OK")
    mode.add_argument("--audit-sample", type=int, metavar="N", help="G-11 stratified sample of cached OK")
    p.add_argument("--data-dir", type=pathlib.Path, default=DEFAULT_DATA_DIR)
    p.add_argument("--since", default=DEFAULT_SINCE)
    p.add_argument("--cache", type=pathlib.Path, required=True, help="JSONL cache, outside data/")
    p.add_argument("--limit", type=int, default=None)
    p.add_argument("--exclude-ids", default="", help="ID[,ID] → stage manual_exclusion")
    p.add_argument("--withhold-ids", type=pathlib.Path, default=None,
                   help="file, one id per line → left untouched (G-11/G-14)")
    p.add_argument("--spend-cap", type=float, default=None, help="USD, G-11: 5.00 − A/B spend − 0.25")
    p.add_argument("--spend-ledger", type=pathlib.Path, default=None)
    p.add_argument("--report", type=pathlib.Path, default=None)
    p.add_argument("--seed", type=int, default=3405)
    p.add_argument("--out", type=pathlib.Path, default=None)
    p.add_argument("--today", default=None, help="YYYY-MM-DD (window reference; default today)")
    return p


def _load_env_files(env_files: Iterable[pathlib.Path]) -> None:
    try:
        from dotenv import load_dotenv
    except ImportError:
        logger.warning("python-dotenv not installed — relying on the process env")
        return
    for f in env_files:
        if f.exists():
            load_dotenv(dotenv_path=f, override=False)


def main(
    argv: list[str] | None = None,
    *,
    env_files: Iterable[pathlib.Path] | None = None,
    router_hook: Callable | None = None,
    http_get: Callable | None = None,
) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    args = _build_parser().parse_args(argv)

    data_dir: pathlib.Path = args.data_dir
    since = parse_dt(args.since)
    if since is None:
        print(f"ERROR: invalid --since {args.since!r}", file=sys.stderr)
        return EXIT_ERROR
    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    for path, flag in ((args.cache, "--cache"), (args.spend_ledger, "--spend-ledger"),
                       (args.report, "--report"), (args.out, "--out")):
        _assert_outside(path, data_dir, flag)
    if not (data_dir / "rejected").is_dir():
        print(f"ERROR: {data_dir}/rejected not found", file=sys.stderr)
        return EXIT_ERROR

    exclude_ids = _split_ids(args.exclude_ids)
    withhold_ids = _read_ids_file(args.withhold_ids)

    if args.dry_run:
        return run_dry(data_dir, since, args.cache, today)

    if args.review:
        return run_review(select_outage_rows(data_dir, since), load_cache(args.cache))

    if args.audit_sample is not None:
        if args.out is None:
            print("ERROR: --audit-sample needs --out", file=sys.stderr)
            return EXIT_ERROR
        return run_audit_sample(
            select_outage_rows(data_dir, since), load_cache(args.cache),
            args.audit_sample, args.seed, args.out,
            exclude_ids=exclude_ids, withhold_ids=withhold_ids,
        )

    if args.apply:
        code, report = run_apply(
            data_dir, args.cache, since=since, exclude_ids=exclude_ids,
            withhold_ids=withhold_ids, today=today,
            now=dt.datetime.now(dt.timezone.utc), spend_ledger=args.spend_ledger,
        )
        text = json.dumps(report, indent=2, ensure_ascii=False)
        print(text)
        if args.report is not None:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_bytes((text + "\n").encode("utf-8"))
        return code

    # --classify
    if args.spend_cap is None:
        print("ERROR: --classify needs --spend-cap (G-11)", file=sys.stderr)
        return EXIT_ERROR
    rows = select_outage_rows(data_dir, since)
    cache = load_cache(args.cache)
    pending = [r for r in rows if not _is_final(cache.get(r["id"]))]
    if args.limit is not None:
        pending = pending[: args.limit]
    if not pending:
        print("classify: nothing to do (every selected id has a final cached outcome)")
        return EXIT_OK

    # R-12: keys from pipeline/.env then the repo-root .env (override=False), and only
    # THEN import the classifier — its import-time client reads os.environ.
    _load_env_files(env_files if env_files is not None
                    else [_REPO_ROOT / "pipeline" / ".env", _REPO_ROOT / ".env"])
    from pipeline.news.classifier import build_router_from_env

    router = build_router_from_env()
    if router_hook is not None:
        router_hook(router)
    if not router.any_key_present:
        print(f"ERROR: no API key ({' / '.join(router.key_env_names)})", file=sys.stderr)
        return EXIT_ERROR
    logger.info("classify: primary=%s backup=%s", router.primary_label, router.backup_label)
    router.preflight()

    ledger = args.spend_ledger or args.cache.with_name(args.cache.stem + ".spend.json")
    _assert_outside(ledger, data_dir, "--spend-ledger")
    meter = SpendMeter(
        args.spend_cap, ledger,
        api_key=os.environ.get("OPENROUTER_API_KEY", "").strip() or None,
        http_get=http_get,
    )
    meter.start()
    code = run_classify(rows, args.cache, router, meter, limit=args.limit)
    final_cache = load_cache(args.cache)
    print(f"exit={code} spend_usd={meter.total:.6f} cap={meter.cap} "
          f"cached_final={sum(1 for r in rows if _is_final(final_cache.get(r['id'])))} "
          f"cached_api_error={sum(1 for r in rows if final_cache.get(r['id']) and not _is_final(final_cache.get(r['id'])))} "
          f"uncached={sum(1 for r in rows if r['id'] not in final_cache)} "
          f"failovers={router.failovers}")
    return code


if __name__ == "__main__":
    sys.exit(main())
