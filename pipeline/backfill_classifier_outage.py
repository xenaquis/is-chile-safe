def _load_json(path: pathlib.Path) -> dict:
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return data if isinstance(data, dict) else {}


def _incidents(path: pathlib.Path) -> list[dict]:
    return list(_load_json(path).get("incidents") or [])


def _raw_lni(current_path: pathlib.Path):
    """last_new_incident_at as stored (sentinel "<absent>" when the key is missing)."""
    data = _load_json(current_path)
    return data.get("last_new_incident_at", "<absent>")


def run_apply(
    data_dir: pathlib.Path,
    cache_path: pathlib.Path,
    *,
    since: dt.datetime,
    exclude_ids: set[str],
    withhold_ids: set[str],
    today: dt.date,
    now: dt.datetime,
    spend_ledger: pathlib.Path | None = None,
) -> tuple[int, dict]:
    from pipeline.news import centroids, dedup, resolver, store
    from pipeline.news.feeds import source_headline
    from pipeline.news.fidelity import forbidden_term, guard_title_en
    from pipeline.news.schema import ClassifierOutput, IncidentRecord
    from pydantic import ValidationError

    current_path = data_dir / "current.json"
    archive_dir = data_dir / "archive"
    cutoff = today - dt.timedelta(days=WINDOW_DAYS)

    scanned = _scan(data_dir, since)
    rows = sorted((row for _, row in scanned), key=_order_key)
    cache = load_cache(cache_path)

    lni_before = _raw_lni(current_path)

    stage_of: dict[str, tuple[str, str]] = {}  # id -> (stage, reclassified_model)
    candidates: list[dict] = []
    cand_meta: dict[int, tuple[str, str]] = {}  # id(incident) -> (row id, model label)
    api_error_breakdown: Counter = Counter()
    counts = Counter()

    for row in rows:
        rid = row["id"]
        rec = cache.get(rid)
        model_label = f"{rec.get('provider')}:{rec.get('model')}" if rec else "manual"
        if rid in exclude_ids:
            stage_of[rid] = ("manual_exclusion", model_label)
            counts["excluded"] += 1
            continue
        if rid in withhold_ids:
            counts["withheld"] += 1
            continue
        if rec is None:
            counts["not_attempted"] += 1
            continue
        outcome = rec.get("outcome")
        if outcome == API_ERROR or outcome not in FINAL_OUTCOMES:
            counts["api_error_remaining"] += 1
            err = rec.get("error")
            api_error_breakdown[err if err in ("empty_content", "finish_length") else "other"] += 1
            continue
        if outcome == "not_crime":
            stage_of[rid] = ("low_confidence", model_label)
            continue
        if outcome == "parse_error":
            stage_of[rid] = ("parse_error", model_label)
            continue
        # OK → the scrape_news.py OK path: resolve_cut → get_centroid → build_incident.
        try:
            out = ClassifierOutput.model_validate(rec.get("output") or {})
        except ValidationError:
            stage_of[rid] = ("parse_error", model_label)
            continue
        resolved = resolver.resolve_cut(out.commune_name, out.region_hint) if out.commune_name else None
        if resolved is None:
            stage_of[rid] = ("commune_null" if not out.commune_name else "resolver_fail", model_label)
            continue
        cut, slug = resolved
        centroid = centroids.get_centroid(cut)
        if centroid is None:
            stage_of[rid] = ("centroid_fail", model_label)
            continue
        lat, lng = centroid
        # FID-01 (G-28): the outlet's verbatim headline is the stored Spanish
        # headline; the classifier's title_en passes the kinship guard (FID-07).
        outlet = row.get("outlet") or ""
        title_src = source_headline(row.get("title") or "", outlet)
        if not title_src.strip():
            # Pre-push F-1: build_incident raises on an empty title_src — reject
            # this row only instead of aborting the whole apply.
            stage_of[rid] = ("empty_title", model_label)
            continue
        title_en, fell_back = guard_title_en(title_src, out.title_en, outlet)
        if forbidden_term(title_src) or forbidden_term(title_en):
            stage_of[rid] = ("editorial_filter", model_label)  # G-29
            counts["editorial_filtered"] += 1
            continue
        if fell_back:
            counts["title_en_fallbacks"] += 1
        incident = store.build_incident(
            url=row["url"], cut=cut, lat=lat, lng=lng,
            title_src=title_src, title_en=title_en,
            date=row.get("date") or "", outlet=outlet,
            family=out.family, slug=slug,
        )
        if incident is None:
            stage_of[rid] = ("url_rejected", model_label)
            continue
        # merge_and_write validates the WHOLE payload and silently skips the write
        # on any invalid record — pre-validate each candidate so one bad row cannot
        # block the batch.
        try:
            IncidentRecord.model_validate(incident)
            if _parse_date(incident["date"]) is None:
                raise ValueError("date")
        except (ValidationError, ValueError):
            stage_of[rid] = ("invalid_record", model_label)
            continue
        candidates.append(incident)
        cand_meta[id(incident)] = (rid, model_label)

    # Dedup against EXISTING incidents first (existing wins): current.json plus every
    # archive month a candidate would age into.
    existing = _incidents(current_path)
    months = sorted({c["date"][:7] for c in candidates if _parse_date(c["date"]) < cutoff})
    for month in months:
        existing += _incidents(archive_dir / f"{month}.json")
    # Full id set across current + ALL archive months (idempotent recovery: an id
    # already published — e.g. a crash between merge and the rejected rewrite — is
    # counted as already_present and removed from rejected/, never merged twice).
    all_ids = {inc.get("id") for inc in _incidents(current_path)}
    if archive_dir.is_dir():
        for month_path in archive_dir.glob("*.json"):
            all_ids |= {inc.get("id") for inc in _incidents(month_path)}

    already_present = [c for c in candidates if c["id"] in all_ids]
    fresh = [c for c in candidates if c["id"] not in all_ids]
    survivors = dedup.deduplicate(existing + fresh)  # existing first → existing wins
    survivor_objs = {id(x) for x in survivors}
    accepted: list[dict] = []
    for c in fresh:
        if id(c) in survivor_objs:
            accepted.append(c)
        else:
            row_id, model_label = cand_meta[id(c)]
            stage_of[row_id] = ("dedup_duplicate", model_label)

    accepted_in_window = sum(1 for c in accepted if _parse_date(c["date"]) >= cutoff)
    accepted_archived = len(accepted) - accepted_in_window

    if accepted:
        with _store_writes_preserve_eol():
            store.merge_and_write(
                accepted, current_path, archive_dir,
                window_days=WINDOW_DAYS, today=today, now=now,
                bump_last_new=False,  # G-07(a) / R-02: only live runs refresh G-05 evidence
            )
        # merge_and_write logs and skips the write on a validation failure — verify.
        written = {inc.get("id") for inc in _incidents(current_path)}
        for month in {c["date"][:7] for c in accepted}:
            written |= {inc.get("id") for inc in _incidents(archive_dir / f"{month}.json")}
        missing = [c["id"] for c in accepted if c["id"] not in written]
        if missing:
            logger.error("apply: %d accepted ids not written (merge validation?) — "
                         "rejected/ left untouched", len(missing))
            return EXIT_ERROR, {"error": "merge_not_written", "missing": missing[:20]}

    lni_after = _raw_lni(current_path)
    if lni_after != lni_before:
        logger.error("apply: last_new_incident_at changed (%r -> %r) — G-07(a) violated",
                     lni_before, lni_after)
        return EXIT_ERROR, {"error": "last_new_incident_at_changed"}

    # Row ids (== make_id(url) in real data, but never assumed).
    removed_ids = {cand_meta[id(c)][0] for c in accepted + already_present}
    _rewrite_rejected(data_dir, since, removed_ids, stage_of, now)

    by_stage = Counter(stage for stage, _ in stage_of.values())
    frozen_ids = {r["id"] for r in rows if _frozen(r)}
    resolved_ids = removed_ids | set(stage_of)
    spend = None
    if spend_ledger is not None and spend_ledger.exists():
        spend = json.loads(spend_ledger.read_text(encoding="utf-8")).get("total_usd")
    by_file = Counter(name for name, _ in scanned)
    report = {
        "selected": len(rows),
        "by_file": dict(sorted(by_file.items())),
        "frozen_subset": len(frozen_ids),
        "frozen_subset_resolved": len(frozen_ids & resolved_ids),
        "accepted_in_window": accepted_in_window,
        "accepted_archived": accepted_archived,
        "already_present": len(already_present),
        "by_stage": dict(sorted(by_stage.items())),
        "api_error_remaining": counts["api_error_remaining"],
        "api_error_breakdown": {k: api_error_breakdown.get(k, 0)
                                for k in ("empty_content", "finish_length", "other")},
        "not_attempted": counts["not_attempted"],
        "withheld": counts["withheld"],
        "excluded": counts["excluded"],
        "fidelity": {"title_en_fallbacks": counts["title_en_fallbacks"],
                     "editorial_filtered": counts["editorial_filtered"]},
        "spend_usd": spend,
        "window_cutoff": cutoff.isoformat(),
        "last_new_incident_at_before": None if lni_before == "<absent>" else lni_before,
        "last_new_incident_at_after": None if lni_after == "<absent>" else lni_after,
    }
    return EXIT_OK, report


def _rewrite_rejected(
    data_dir: pathlib.Path,
    since: dt.datetime,
    removed_ids: set[str],
    stage_of: dict[str, tuple[str, str]],
    now: dt.datetime,
) -> None:
    """Rewrite each touched month file in place: drop accepted ids, set the real stage
    on the others (key order preserved, reclassified_* appended), leave API_ERROR /
    uncached / withheld rows byte-equal. A file with no change is not written."""
    stamp = _iso_z(now)
    for path in _month_files(data_dir, since):
        envelope = _load_envelope(path)
        changed = False
        new_items = []
        for row in envelope["items"]:
            if isinstance(row, dict) and _is_selected(row, since):
                rid = row.get("id")
                if rid in removed_ids:
                    changed = True
                    continue
                if rid in stage_of:
                    stage, model_label = stage_of[rid]
                    row = dict(row)
                    row["rejection_stage"] = stage
                    row["reclassified_at"] = stamp
                    row["reclassified_model"] = model_label
                    changed = True
            new_items.append(row)
        if not changed:
            continue
        envelope["items"] = new_items
        envelope["generated"] = now.astimezone(dt.timezone.utc).isoformat()
        eol_preserving_write_json(path, envelope)
        logger.info("apply: rewrote %s", path.name)


