EXIT_OK = 0
EXIT_ERROR = 1
EXIT_CAP = 3
EXIT_EXHAUSTED = 4
EXIT_STRATUM = 5


def run_classify(
    rows: list[dict],
    cache_path: pathlib.Path,
    router,
    meter: SpendMeter,
    *,
    limit: int | None = None,
    now_fn: Callable[[], dt.datetime] = lambda: dt.datetime.now(dt.timezone.utc),
) -> int:
    """Classify every selected row without a final cached outcome, in selection order.

    BF-04: no per-run time budget — the 1200 s G-09 budget protects the 30-min
    Actions job; this local tool has no such limit (3,695 ms/item measured for
    DeepSeek at gate R1 → 1200 s would cover only ~325 items).
    """
    from pipeline.news.feeds import strip_html

    router.budget_s = float("inf")

    cache = load_cache(cache_path)
    todo = [r for r in rows if not _is_final(cache.get(r["id"]))]
    if limit is not None:
        todo = todo[:limit]
    logger.info("classify: %d selected, %d to attempt", len(rows), len(todo))

    cache_path.parent.mkdir(parents=True, exist_ok=True)
    last_written: dict[str, object] = {}
    with open(cache_path, "a", encoding="utf-8", newline="") as fh:

        def _write(key: str, res) -> None:
            fh.write(json.dumps(_cache_line(key, res, now_fn()), ensure_ascii=False) + "\n")
            fh.flush()
            last_written[key] = res

        for n, row in enumerate(todo, 1):
            if meter.would_exceed():
                logger.warning(
                    "classify: spend cap %.4f reached (total %.4f) — stopping, exit 3",
                    meter.cap, meter.total,
                )
                return EXIT_CAP
            # FID-06: the stored raw description carries HTML entities (2,782/4,427
            # rows) — hand the classifier the same entity-free text as the live path.
            res = router.classify(row["title"] or "", strip_html(row["description"] or ""),
                                  key=row["id"])
            if res is None:
                logger.error("classify: router exhausted after %d attempts — exit 4", n - 1)
                return EXIT_EXHAUSTED
            _write(row["id"], res)
            meter.charge(res)
            # NB-06: a breaker trip re-dispatched the tripping streak to the backup;
            # one cache line per (key, result) supersedes that key's API_ERROR line.
            for rkey, rres in router.pop_redispatched():
                if not rkey:
                    continue
                already = last_written.get(rkey) is rres
                _write(rkey, rres)
                if not already:
                    meter.charge(rres)
            if n % 100 == 0:
                logger.info("classify: %d/%d, spend %.4f", n, len(todo), meter.total)
    meter.persist()
    return EXIT_OK


