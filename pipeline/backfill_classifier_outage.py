def parse_dt(value: str | None) -> dt.datetime | None:
    """ISO datetime → aware UTC datetime. A trailing "Z" is normalized; a naive value
    is treated as UTC. Returns None when unparseable."""
    if not isinstance(value, str) or not value.strip():
        return None
    s = value.strip()
    if s.endswith(("Z", "z")):
        s = s[:-1] + "+00:00"
    try:
        parsed = dt.datetime.fromisoformat(s)
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=dt.timezone.utc)
    return parsed.astimezone(dt.timezone.utc)


def _parse_date(value: str | None) -> dt.date | None:
    try:
        return dt.date.fromisoformat((value or "")[:10])
    except ValueError:
        return None


def _iso_z(moment: dt.datetime) -> str:
    return moment.astimezone(dt.timezone.utc).isoformat().replace("+00:00", "Z")


def _detect_eol(path: pathlib.Path) -> str:
    """Line ending of an existing file; LF for a new file (data/incidents is LF in git)."""
    try:
        return "\r\n" if b"\r\n" in path.read_bytes() else "\n"
    except FileNotFoundError:
        return "\n"


def eol_preserving_write_json(path: pathlib.Path, data, compact: bool = False) -> None:
    """Atomic JSON write that keeps the file's existing line ending.

    Same format as pipeline.shared.atomic_write.atomic_write_json (indent=2,
    ensure_ascii=False, no trailing newline), but written as BYTES: Path.write_text
    translates "\\n" to CRLF on Windows, which would flip every line of the LF files
    under data/incidents when this tool is run locally (Task 3 apply)."""
    eol = _detect_eol(path)
    trailing = False
    if path.exists():
        trailing = path.read_bytes().endswith(b"\n")
    if compact:
        text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    else:
        text = json.dumps(data, ensure_ascii=False, indent=2)
    if trailing:
        text += "\n"
    if eol != "\n":
        text = text.replace("\n", eol)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_bytes(text.encode("utf-8"))
    os.replace(tmp, path)


@contextlib.contextmanager
def _store_writes_preserve_eol():
    """Route pipeline.news.store's atomic writes through the EOL-preserving writer
    for the duration of the apply (scoped; the shared util is left untouched because
    the local CEAD scraper's CRLF outputs depend on its current behaviour)."""
    from pipeline.news import store

    original = store.atomic_write_json
    store.atomic_write_json = eol_preserving_write_json
    try:
        yield
    finally:
        store.atomic_write_json = original


def _assert_outside(path: pathlib.Path | None, data_dir: pathlib.Path, flag: str) -> None:
    if path is None:
        return
    p = path.resolve()
    d = data_dir.resolve()
    if p == d or d in p.parents:
        raise SystemExit(f"ERROR: {flag} {path} must be outside the data dir {data_dir}")


def _read_ids_file(path: pathlib.Path | None) -> set[str]:
    if path is None:
        return set()
    ids: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            ids.add(line)
    return ids


def _split_ids(value: str | None) -> set[str]:
    if not value:
        return set()
    return {part.strip() for part in value.split(",") if part.strip()}


