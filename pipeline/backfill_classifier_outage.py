def run_dry(data_dir: pathlib.Path, since: dt.datetime, cache_path: pathlib.Path,
            today: dt.date, out=None) -> int:
    out = out or sys.stdout
    scanned = _scan(data_dir, since)
    rows = [row for _, row in scanned]
    cache = load_cache(cache_path)  # read-only; never created
    cutoff = today - dt.timedelta(days=WINDOW_DAYS)
    by_file = Counter(name for name, _ in scanned)
    by_day = Counter((parse_dt(r["first_seen"]).date().isoformat()) for r in rows)
    by_pub_month = Counter((r.get("date") or "")[:7] or "?" for r in rows)
    dates = sorted(d for d in (_parse_date(r.get("date")) for r in rows) if d)
    priority_days = Counter(r["date"] for r in rows
                            if (d := _parse_date(r.get("date"))) and PRIORITY_START <= d <= PRIORITY_END)
    already = sum(1 for r in rows if _is_final(cache.get(r["id"])))
    cached_api_error = sum(1 for r in rows
                           if cache.get(r["id"]) and not _is_final(cache.get(r["id"])))
    would_archive = sum(1 for r in rows if (d := _parse_date(r.get("date"))) and d < cutoff)
    print(f"selected={len(rows)}", file=out)
    print(f"by_file={json.dumps(dict(sorted(by_file.items())))}", file=out)
    print(f"frozen_subset={sum(1 for r in rows if _frozen(r))}", file=out)
    print(f"by_first_seen_day={json.dumps(dict(sorted(by_day.items())))}", file=out)
    print(f"by_pub_month={json.dumps(dict(sorted(by_pub_month.items())))}", file=out)
    print(f"priority_days_{PRIORITY_START}..{PRIORITY_END}={json.dumps(dict(sorted(priority_days.items())))}", file=out)
    print(f"date_range={dates[0] if dates else None}..{dates[-1] if dates else None}", file=out)
    print(f"window_cutoff={cutoff}", file=out)
    print(f"would_archive={would_archive}", file=out)
    print(f"already_cached={already}", file=out)
    print(f"cached_api_error={cached_api_error}", file=out)
    print(f"planned_calls={len(rows) - already}", file=out)
    return EXIT_OK


